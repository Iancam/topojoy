/**
 * This script generates the api.ts file with imports and exports
 * for all the netlify functions.
 *
 * you need to edit ts.config.json to include the netlify/functions directory as @functions
 * same with vitest.config.ts
 */
import { readdir, readFile, writeFile } from "node:fs/promises";

// generate api.ts file with imports and exports
const files = await readdir("./netlify/functions");
const verbose = process.argv.slice(2).includes("--verbose");
if (verbose) {
  console.log("Verbose mode enabled");
}
const toApiEndpoint = async (file: string) => {
  const filename = file.replace(".ts", "");
  const regex = /^([a-z]+(?:-[a-z]+)*)-(create|update|upsert|delete|get|list)$/;
  const match = filename.match(regex);
  if (!match) {
    // console.warn(`File ${file} does not match pattern`);
    return null;
  }

  const capitalize = (str: string) =>
    str.charAt(0).toUpperCase() + str.slice(1);

  const resourceName = match[1]
    .split("-")
    .map((word) => capitalize(word))
    .join("");
  const action = match[2];
  const resourceAction = `${resourceName}${capitalize(action)}`;

  const method = {
    create: "POST",
    update: "PATCH",
    upsert: "PUT",
    delete: "DELETE",
    get: "GET",
    list: "GET",
  };

  // Check if input/output exports exist
  let hasInput = false;
  let hasOutput = false;
  try {
    const modulePath = `../netlify/functions/${filename}.ts`;
    const module = await import(modulePath);
    hasInput = module.input !== undefined;
    hasOutput = module.output !== undefined;
  } catch (error) {
    if (verbose) {
      console.warn(`Could not import ${filename}, using z.any() for schemas`);
    }
  }

  const importParts = [];
  if (hasInput) importParts.push(`input as ${resourceAction}Input`);
  if (hasOutput) importParts.push(`output as ${resourceAction}Output`);

  const importCode =
    importParts.length > 0
      ? `import { ${importParts.join(", ")} } from '../netlify/functions/${filename}';`
      : null;

  const resource = {
    name: resourceName,
    action: action,
    resourceAction,
    filename: filename,
    importCode: importCode,
    method: method[action as keyof typeof method],
    hasInput,
    hasOutput,
  };

  return resource;
};

const apiEndpoints = (await Promise.all(files.map(toApiEndpoint))).filter(
  (api) => api !== null,
);

const ending = (await readFile("./scripts/buildAPI.txt.ts")).toString();
const additionalImports = ending
  .split("\n")
  .filter((line) => line.startsWith("import"))
  .join("\n");
const endpointImports = apiEndpoints
  .map((endpoint) => endpoint.importCode)
  .filter((code) => code !== null)
  .join("\n");
const imports = [additionalImports, endpointImports].join("\n");

let endpointCode = apiEndpoints
  .map((endpoint) => {
    const inputType = endpoint.hasInput
      ? `${endpoint.resourceAction}Input`
      : "z.any()";
    const outputType = endpoint.hasOutput
      ? `${endpoint.resourceAction}Output`
      : "z.any()";

    return `  {
    filename: "${endpoint.filename}",
    action: "${endpoint.action}",
    method: "${endpoint.method}",
    name: "${endpoint.name.toLowerCase()}",
    InputType: ${inputType},
    OutputType: ${outputType},
  }`;
  })
  .join(",\n");
endpointCode = `const endpoints = [\n${endpointCode}\n] as const`;

// Group endpoints by resource name for the API object
const groupedEndpoints = apiEndpoints.reduce(
  (acc, endpoint) => {
    if (!acc[endpoint.name]) acc[endpoint.name] = [];
    acc[endpoint.name].push(endpoint);
    return acc;
  },
  {} as Record<string, typeof apiEndpoints>,
);

// Generate the API object with proper structure for autocomplete
let apiObjectCode = "export const api = {\n";
for (const [resourceName, endpoints] of Object.entries(groupedEndpoints)) {
  apiObjectCode += `  ${resourceName}: {\n`;
  for (const endpoint of endpoints) {
    const endpointIndex = apiEndpoints.indexOf(endpoint);
    apiObjectCode += `    ${endpoint.action}: buildClientFunction(endpoints[${endpointIndex}]),\n`;
  }
  apiObjectCode += `  },\n`;
}
apiObjectCode += "};";

const clientBuilder = ending
  .split("\n")
  .filter((line) => !line.startsWith("import"))
  .filter((line) => !line.includes("API_OBJECT_PLACEHOLDER"))
  .join("\n");

const header = `/**
 * ⚠️ AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * 
 * This file is automatically generated by scripts/apiGenerator.ts
 * 
 * To regenerate:
 *   npm run api:generate
 * 
 * To watch for changes:
 *   npm run api:watch
 * 
 * To add type-safe endpoints, export 'input' and 'output' Zod schemas
 * from your netlify function files.
 */

`;

const opFile = `${header}${imports}\n\n${endpointCode}\n\n${clientBuilder}\n\n${apiObjectCode}`;

await writeFile("./src/_generatedAPI.ts", opFile);
