// lumaprintPrices.js (or another util file)
export function estimatePriceForPrintType(printType, targetSize) {
  const { col, subcategoryId, table } = choices[printType];
  return estimatePriceFromTable(table, targetSize, col);
}
/**
 * table: e.g. framedFineArt
 * targetSize: [width, height] in inches
 * columnIndex:
 *   1 = first price column (NO MAT / 1.25IN STRETCHED CANVAS / ARCHIVAL MATTE)
 *   2 = second price column, etc.
 */
function estimatePriceFromTable(table, targetSize, columnIndex = 1) {
  const header = table[0]; // ["SIZE", "NO MAT", '1" MAT', ...]
  const rows = table.slice(1); // [[[w,h], p1, p2,...], ...]

  const { width: tw, height: th } = targetSize;
  const targetArea = tw * th;
  const targetRatio = tw / th;

  let bestRow = null;
  let bestScore = Infinity;

  for (const row of rows) {
    const [size, ...prices] = row;
    const [w, h] = size;
    const price = prices[columnIndex - 1];

    // skip n/a entries
    if (typeof price !== "number" || Number.isNaN(price)) continue;

    const area = w * h;
    const ratio = w / h;

    // log-space differences so big sizes don't dominate
    const areaDiff = Math.abs(Math.log(area / targetArea));
    const ratioDiff = Math.abs(Math.log(ratio / targetRatio));

    // weight: mostly area, some aspect ratio
    const score = areaDiff * 0.7 + ratioDiff * 0.3;

    if (score < bestScore) {
      bestScore = score;
      bestRow = { size: [w, h], price };
    }
  }

  if (!bestRow) return null;

  const [bw, bh] = bestRow.size;
  const baseArea = bw * bh;
  const scale = targetArea / baseArea;

  const estimatedPrice = Number((bestRow.price * scale).toFixed(2));

  return {
    estimatedPrice,
    nearestSize: bestRow.size,
    basePrice: bestRow.price,
    columnLabel: header[columnIndex], // e.g. "NO MAT" or '1" MAT'
  };
}
